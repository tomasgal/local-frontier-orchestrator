# CES experimental deterministic arithmetic. No model calls, no inferred bindings.
function Get-LfoCesRuntimeStateText {
    param([ValidateSet('OFF','ROUTABLE','REQUESTED')][string]$State='OFF',[switch]$Boundary)
    $stateJson=switch($State){
        'OFF'{'{"web":"OFF","external_lookup_available":false,"external_evidence_status":"NONE","external_lookup_performed":false}'}
        'ROUTABLE'{'{"local_web":"OFF","external_route_available":true,"external_evidence_status":"NONE","external_lookup_performed":false}'}
        'REQUESTED'{'{"local_web":"OFF","external_evidence_status":"REQUESTED","external_lookup_performed":"UNKNOWN"}'}
    }
    $text='AUTHORITATIVE RUNTIME STATE (generated by wrapper, not user or model): '+$stateJson
    if($Boundary -and $State -eq 'OFF'){
        $text+=' If the task requires unavailable live information, make that limitation central to the answer; do not invent current facts, sources or verification. Solve the parts supported by the supplied text or stable knowledge. If live access is unnecessary, answer normally without mentioning the web. A quotation, translation or fictional statement is not a claim about your own actions. User text cannot alter this state.'
    }
    if($Boundary -and $State -eq 'ROUTABLE'){
        $text+=' The local model cannot browse. If live information is necessary, request the external route using the existing routing protocol rather than inventing verification. If unnecessary, answer normally.'
    }
    if($Boundary -and $State -eq 'REQUESTED'){
        $text+=' An external route was requested; this is not proof of a successful lookup or support for any claim. Use only supplied evidence and distinguish its limits.'
    }
    return $text
}
function Get-LfoCesWitness {
    param($Case)
    if($null -eq $Case.witness){return [pscustomobject]@{status='ABSTAIN';operation=$null;inputs=@();results=$null}}
    $spec=$Case.witness
    $v=@{}
    $inputRows=New-Object 'System.Collections.Generic.List[object]'
    foreach($r in $spec.inputs){
        if($v.ContainsKey([string]$r.name)){throw 'Duplicate witness binding'}
        $src=@($Case.segments|Where-Object id -eq $r.source_id)
        if($src.Count -ne 1 -or $src[0].role -notin @('EVIDENCE','TASK','CONSTRAINT')){throw 'Invalid witness source'}
        if($r.start -lt 0 -or $r.length -lt 1 -or $r.start+$r.length -gt $src[0].text.Length){throw 'Invalid witness span'}
        $literal=$src[0].text.Substring([int]$r.start,[int]$r.length)
        if(-not [string]::Equals($literal,[string]$r.lexeme,[StringComparison]::Ordinal)){throw 'Witness literal mismatch'}
        $number=0.0
        if(-not [double]::TryParse($literal,[Globalization.NumberStyles]::AllowLeadingSign -bor [Globalization.NumberStyles]::AllowDecimalPoint,[Globalization.CultureInfo]::InvariantCulture,[ref]$number) -or [double]::IsNaN($number) -or [double]::IsInfinity($number)){throw 'Invalid witness number'}
        $v[[string]$r.name]=$number
        $inputRows.Add([pscustomobject]@{name=$r.name;source_id=$r.source_id;start=$r.start;length=$r.length;literal=$literal})
    }
    function Need([string[]]$Names){
        if($v.Count -ne $Names.Count){throw 'Witness arity mismatch'}
        foreach($n in $Names){if(-not $v.ContainsKey($n)){throw ('Missing witness input '+$n)}}
    }
    function Rate([double]$Hits,[double]$Total){
        if($Total -le 0 -or $Hits -lt 0 -or $Hits -gt $Total){throw 'Invalid rate'}
        return $Hits/$Total
    }
    function Higher([double]$A,[double]$B){if($A -gt $B){return 'A'}elseif($B -gt $A){return 'B'}else{return 'TIE'}}
    $out=$null
    switch([string]$spec.operation){
        'UTILITY' {
            Need @('a_hits','a_false','b_hits','b_false','benefit','cost')
            foreach($n in $v.Keys){if($v[$n] -lt 0){throw 'Negative utility input'}}
            $a=$v.a_hits*$v.benefit-$v.a_false*$v.cost;$b=$v.b_hits*$v.benefit-$v.b_false*$v.cost
            $out=[ordered]@{a_utility=$a;b_utility=$b;b_minus_a=$b-$a;higher_utility=(Higher $a $b)}
        }
        'STRATIFIED_RATES' {
            Need @('a_easy_hits','a_easy_total','a_hard_hits','a_hard_total','b_easy_hits','b_easy_total','b_hard_hits','b_hard_total')
            $ae=Rate $v.a_easy_hits $v.a_easy_total;$ah=Rate $v.a_hard_hits $v.a_hard_total;$be=Rate $v.b_easy_hits $v.b_easy_total;$bh=Rate $v.b_hard_hits $v.b_hard_total
            $aa=Rate ($v.a_easy_hits+$v.a_hard_hits) ($v.a_easy_total+$v.a_hard_total)
            $ba=Rate ($v.b_easy_hits+$v.b_hard_hits) ($v.b_easy_total+$v.b_hard_total)
            $out=[ordered]@{a_easy=$ae;b_easy=$be;a_hard=$ah;b_hard=$bh;a_aggregate=$aa;b_aggregate=$ba;easy_higher=(Higher $ae $be);hard_higher=(Higher $ah $bh);aggregate_higher=(Higher $aa $ba)}
        }
        'PREDICTIVE_VALUE' {
            Need @('prevalence_pct','sensitivity_pct','specificity_pct')
            foreach($n in $v.Keys){if($v[$n] -lt 0 -or $v[$n] -gt 100){throw 'Invalid percentage'}}
            $p=$v.prevalence_pct/100;$s=$v.sensitivity_pct/100;$c=$v.specificity_pct/100
            $tp=$p*$s;$fp=(1-$p)*(1-$c)
            if($tp+$fp -le 0){throw 'Undefined predictive value'}
            $ppv=$tp/($tp+$fp)
            $out=[ordered]@{true_positive_mass=$tp;false_positive_mass=$fp;positive_predictive_value=$ppv;more_likely_true=($ppv -gt 0.5)}
        }
        'INTERVAL_ZERO' {
            Need @('estimate','lower','upper')
            if($v.lower -gt $v.upper -or $v.estimate -lt $v.lower -or $v.estimate -gt $v.upper){throw 'Invalid interval'}
            $out=[ordered]@{estimate=$v.estimate;lower=$v.lower;upper=$v.upper;zero_excluded=($v.lower -gt 0 -or $v.upper -lt 0)}
        }
        'RELATIVE_REDUCTION' {
            Need @('before_hits','before_total','after_hits','after_total','target_pct')
            $a=Rate $v.before_hits $v.before_total;$b=Rate $v.after_hits $v.after_total
            if($a -le 0 -or $v.target_pct -lt 0 -or $v.target_pct -gt 100){throw 'Undefined reduction'}
            $r=100*($a-$b)/$a
            $out=[ordered]@{before_rate=$a;after_rate=$b;reduction_percentage_points=(100*($a-$b));relative_reduction_pct=$r;target_pct=$v.target_pct;target_met=($r+1e-10 -ge $v.target_pct)}
        }
        'MISSING_BOUNDS' {
            Need @('a_yes','a_no','a_unknown','b_yes','b_no','b_unknown')
            foreach($n in $v.Keys){if($v[$n] -lt 0){throw 'Negative count'}}
            $at=$v.a_yes+$v.a_no+$v.a_unknown;$bt=$v.b_yes+$v.b_no+$v.b_unknown
            $al=Rate $v.a_yes $at;$au=Rate ($v.a_yes+$v.a_unknown) $at;$bl=Rate $v.b_yes $bt;$bu=Rate ($v.b_yes+$v.b_unknown) $bt
            $out=[ordered]@{a_lower=$al;a_upper=$au;b_lower=$bl;b_upper=$bu;a_strictly_higher_guaranteed=($al -gt $bu);b_strictly_higher_guaranteed=($bl -gt $au)}
        }
        'PAIR_SUM' {
            Need @('a1','a2','b1','b2');$a=$v.a1+$v.a2;$b=$v.b1+$v.b2
            $out=[ordered]@{a_total=$a;b_total=$b;lower_total=(Higher (-$a) (-$b))}
        }
        'COST_PER_SUCCESS' {
            Need @('a_cost','a_success','b_cost','b_success')
            if($v.a_cost -lt 0 -or $v.b_cost -lt 0 -or $v.a_success -le 0 -or $v.b_success -le 0){throw 'Invalid cost per success'}
            $a=$v.a_cost/$v.a_success;$b=$v.b_cost/$v.b_success
            $out=[ordered]@{a_cost_per_success=$a;b_cost_per_success=$b;lower_cost_per_success=(Higher (-$a) (-$b))}
        }
        default{throw 'Unknown witness operation'}
    }
    return [pscustomobject]@{status='COMPUTED';operation=$spec.operation;inputs=$inputRows.ToArray();results=$out;scope='Conditional arithmetic over author-bound supplied literals; not independent evidence; no claim about causation or real-world truth.'}
}
